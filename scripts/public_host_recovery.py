class RecoveryError(Exception):
    """Static diagnostics only."""


def digest(value):
    return hashlib.sha256(json.dumps(value, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


def firewall_policy(raw):
    result = []
    for line in raw.splitlines():
        if line.startswith('# Generated by iptables-save ') or line.startswith('# Generated by ip6tables-save ') or line.startswith('# Completed on '):
            continue
        if line.startswith('#') or not line:
            raise RecoveryError('unknown firewall serialization')
        result.append(re.sub(r'^(:\S+ \S+) \[\d+:\d+\]$', r'\1 [COUNTERS]', line))
    if not result or result[-1] != 'COMMIT':
        raise RecoveryError('incomplete firewall snapshot')
    return result


